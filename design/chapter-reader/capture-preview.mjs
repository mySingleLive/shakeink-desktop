// 用无界面 Chromium 渲染本地设计稿（file URL，无监听服务），输出审核截图。
import { chromium } from "playwright"
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1400, height: 1000 }, deviceScaleFactor: 1 })
const errs = []; p.on("pageerror", e => errs.push(e.message))
await p.goto("file://" + process.cwd() + "/design/chapter-reader/index.html")
const ctl = (s, v) => p.click(`.controls button[data-set="${s}"][data-v="${v}"]`)
const pop = (s, v) => p.click(`.reader-pop button[data-set="${s}"][data-v="${v}"]`)
const out = n => p.screenshot({ path: `design/chapter-reader/${n}.png` })
await out("preview-paper")
await p.click('[data-act="pop"]'); await out("preview-paper-settings")
await p.click('[data-toggle="showVolume"]'); await p.click('[data-toggle="showWords"]'); await pop("align", "left")
const head = await p.$eval(".chapter-head", el => ({ align: getComputedStyle(el).textAlign, vol: !!el.querySelector(".vol"), no: !!el.querySelector(".no"), words: el.textContent.includes("字"), end: document.querySelector(".chapter-end").textContent }))
await out("preview-paper-left-hidden")
await p.click('[data-act="pop"]'); await ctl("view", "compare"); await out("preview-compare-paper")
await ctl("theme", "ink"); await out("preview-compare-ink")
await ctl("view", "new"); await ctl("width", "narrow"); await out("preview-ink-narrow")
console.log(JSON.stringify({ errs, head }))
await b.close()
