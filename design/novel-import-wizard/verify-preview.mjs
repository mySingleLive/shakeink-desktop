// 只核对本审核稿：无头 Chrome 打开 file://，阻断网络，逐步点击并截图。
import { chromium } from 'playwright'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { dirname, join } from 'node:path'
import { mkdirSync, writeFileSync } from 'node:fs'

const here = dirname(fileURLToPath(import.meta.url)), out = join(here, 'screens')
mkdirSync(out, { recursive: true })
const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' })
const results = [], errors = [], checks = []
const expect = (ok, what) => { checks.push({ ok: !!ok, what }); if (!ok) errors.push('断言失败：' + what) }

async function open(theme, w, h, scenario = 'normal', fail = true, motion = 'no-preference') {
  const page = await browser.newPage({ viewport: { width: w, height: h }, reducedMotion: motion })
  await page.route(/^https?:/, route => route.abort())
  page.on('pageerror', e => errors.push(`${theme}/${w}/${scenario}: ${e.message}`))
  page.on('console', m => { if (m.type() === 'error') errors.push(`${theme}/${w}/${scenario}: ${m.text()}`) })
  await page.goto(pathToFileURL(join(here, 'wizard.html')).href)
  await page.evaluate(([t, s, f]) => { window.postMessage({ type: 'theme', theme: t }, '*'); window.postMessage({ type: 'reset', scenario: s, fail: f }, '*') }, [theme, scenario, fail])
  await page.waitForTimeout(150)
  const tag = `${theme}-${w}${scenario === 'normal' ? '' : '-' + scenario}`
  const shot = async name => { await page.waitForTimeout(150); await page.screenshot({ path: join(out, `${tag}-${name}.png`) }); results.push({ tag, name, title: await page.textContent('#title') }) }
  const click = async sel => { await page.click(sel); await page.waitForTimeout(120) }
  const next = () => click('#foot [data-act=next]')
  const toConfirm = async () => {
    await click('#body [data-act=next]'); await next(); await click('[data-dir]'); await next(); await next()
    await page.waitForSelector('#title:text("选择卷章")', { timeout: 4000 })
  }
  return { page, shot, click, next, toConfirm }
}

